const WHOLESALE_STORAGE_KEY = 'gfi_wholesale_pricelist_data_v2';

export const getStoredWholesalePricelist = (): WholesalePricelistItem[] => {
  try {
    const data = localStorage.getItem(WHOLESALE_STORAGE_KEY);
    if (data) {
      const parsed = JSON.parse(data);
      if (Array.isArray(parsed) && parsed.length > 0) {
        return parsed;
      }
    }
  } catch (e) {
    console.error('Failed to load wholesale pricelist from localStorage', e);
  }
  return WHOLESALE_PRICELIST;
};

export const saveStoredWholesalePricelist = (items: WholesalePricelistItem[]): void => {
  try {
    localStorage.setItem(WHOLESALE_STORAGE_KEY, JSON.stringify(items));
  } catch (e) {
    console.error('Failed to save wholesale pricelist to localStorage', e);
  }
};

export const resetStoredWholesalePricelist = (): WholesalePricelistItem[] => {
  try {
    localStorage.removeItem(WHOLESALE_STORAGE_KEY);
  } catch (e) {
    console.error('Failed to reset wholesale pricelist', e);
  }
  return WHOLESALE_PRICELIST;
};
